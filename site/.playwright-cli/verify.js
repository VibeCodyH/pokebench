async page => {
  const results = [], errors = [], requests = [];
  const check = (condition, name) => { if (!condition) throw new Error(name); results.push(name); };
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => requests.push(request.url()));
  await page.setViewportSize({width:1440,height:1000});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('http://127.0.0.1:8742/');
  await page.locator('#data-state h2').waitFor();
  check((await page.locator('#data-state').innerText()).includes('No runs yet — run the harness.'),'empty state');
  check(!await page.locator('#sample-banner').isVisible(),'no sample banner on real results');
  check(!requests.some(url=>url.endsWith('/runs.sample.json')),'samples never auto-load');
  check(await page.locator('#journey-button').getAttribute('aria-pressed') === 'true','Journey defaults on');
  await page.locator('#data-state [data-load-sample]').click();
  await page.locator('#winners-wall .run-card').first().waitFor();
  check(await page.locator('#sample-banner').isVisible(),'sample banner after explicit load');
  const placement = await page.locator('.station').evaluateAll(els=>Object.fromEntries(els.map(el=>[el.id,[...el.querySelectorAll('.run-card')].map(card=>Number(card.dataset.furthest))])));
  check(JSON.stringify(placement) === JSON.stringify({brock:[7,7],pewter:[5],forest:[4],viridian:[],'route-one':[2],pallet:[0]}),'sample station placement');
  check((await page.locator('#forest .hero-ribbon').innerText()).includes('LOCAL HERO'),'derived local hero');
  await page.locator('#table-button').click();
  check(await page.locator('#table-view').isVisible() && !await page.locator('#journey-view').isVisible(),'Table switch');
  check(await page.locator('#table-cards .run-map').count()===6,'route thumbnail on every table card');
  check(await page.locator('#table-cards .furthest-x').count()===4,'red X only for non-winners');
  check(await page.locator('#table-cards .inspect:disabled').count()===6,'missing VODs disabled');
  check(await page.locator('#table-cards .run-card').first().getAttribute('data-run')==='run-0','milestone then fewer turns');
  await page.locator('#provider-filter').selectOption('api');
  check(await page.locator('#table-cards .run-card').count()===3,'API filter');
  await page.locator('#provider-filter').selectOption('local');
  check(await page.locator('#table-cards .run-card').count()===3,'Ollama local filter');
  check((await page.locator('#table-cards .free').allTextContents()).every(v=>v==='FREE'),'local cost FREE');
  await page.locator('#family-filter').selectOption('Qwen');
  check(await page.locator('#table-cards .run-card').count()===1,'family filter combines with provider');
  await page.locator('#provider-filter').selectOption('api');
  check(await page.locator('#reset-filters').isVisible(),'no matching filters state');
  await page.locator('#reset-filters').click();
  await page.locator('#sort').selectOption('turns');
  check((await page.locator('#table-cards .model-name').allTextContents()).slice(0,2).join('|')==='GPT-6 Astra|Claude Opus 4.8','fewest turns sort');
  await page.locator('#sort').selectOption('cost');
  check((await page.locator('#table-cards .model-name').allTextContents()).slice(0,3).join('|')==='qwen3.8:27b|Llama 4 8B|Mistral Small','lowest cost sort');
  await page.locator('#sort').selectOption('newest');
  check((await page.locator('#table-cards .model-name').allTextContents()).slice(0,2).join('|')==='GPT-6 Astra|Claude Opus 4.8','newest compact timestamp sort');
  await page.locator('#sort').selectOption('milestone');
  for (let i=0;i<4;i++) await page.locator('#table-cards [data-select]').nth(i).click();
  check(await page.locator('#table-cards [data-select]:disabled').count()===2,'compare limited to four');
  await page.locator('#compare-open').click();
  check(await page.locator('#compare-dialog').isVisible(),'compare dialog opens');
  check(await page.locator('#compare-table thead th').count()===5,'four comparison columns');
  for (const metric of ['Furthest milestone','Turns','Tokens (in + out)','Cost','Time','Prompt version']) check((await page.locator('#compare-table').innerText()).includes(metric),'compare metric '+metric);
  check(await page.locator('#compare-sample').isVisible(),'comparison sample disclosure');
  await page.keyboard.press('Escape');
  check(!await page.locator('#compare-dialog').isVisible(),'Escape closes comparison');
  check(await page.locator('#compare-open').evaluate(el=>document.activeElement===el),'comparison returns focus');
  await page.locator('#provider-filter').selectOption('local');
  check(await page.locator('#compare-chips button').count()===4,'selection survives filtering');
  await page.locator('#journey-button').click();
  check(await page.locator('#journey-view [data-select][aria-pressed=true]').count()===4,'selection shared across views');
  await page.locator('#compare-clear').click();
  check(!await page.locator('#compare-tray').isVisible(),'clear selection');
  await page.locator('.rail-link[data-index="5"]').click();
  check(await page.locator('.rail-link[data-index="5"]').getAttribute('aria-current')==='location','rail checkpoint navigation');
  await page.locator('.page-nav a[href="#methodology"]').click();
  check(await page.locator('#method-milestones li').count()===8,'eight methodology milestones');
  check(await page.locator('.timeline-day').count()===3,'timeline groups run dates');
  check(await page.locator('#sample-banner').isVisible(),'sample banner persists through sections');
  check(await page.locator('body').evaluate(el=>el.classList.contains('depth-off')),'reduced motion honored');
  check(await page.locator('.walking-sprite').first().evaluate(el=>getComputedStyle(el).animationName)==='none','walking sprite stops with reduced motion');
  await page.setViewportSize({width:390,height:844});
  await page.locator('.brand').click();
  await page.screenshot({path:'.playwright-cli/verified-mobile.png'});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'390px no horizontal overflow');
  await page.locator('#pallet').evaluate(el=>el.scrollIntoView({behavior:'instant'}));
  await page.screenshot({path:'.playwright-cli/pallet-mobile-v2.png'});
  await page.locator('#table-button').click();
  await page.locator('#provider-filter').selectOption('all');
  await page.screenshot({path:'.playwright-cli/table-mobile.png'});
  for (const width of [320,560,768,1024,1440]) {
    await page.setViewportSize({width,height:900});
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Table width '+width);
    await page.locator('#journey-button').click();
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Journey width '+width);
    await page.locator('#table-button').click();
  }
  await page.screenshot({path:'.playwright-cli/table-desktop.png'});
  await page.locator('#real-data').click();
  await page.locator('#data-state h2').waitFor();
  check(!await page.locator('#sample-banner').isVisible(),'return to real results removes sample mode');
  const sampleResponse = await page.request.get('http://127.0.0.1:8742/runs.sample.json');
  const sample = await sampleResponse.json();
  const fixture = [
    {...sample[0],run_id:'fixture-api-zero',model:'API zero cost',furthest_index:6,beat_brock:false,cost_usd:0,turns_used:88,milestones:[{key:'pewter_gym',label:'Entered gym',turn:88}],youtube_url:'https://www.youtube.com/watch?v=example'},
    {...sample[0],run_id:'fixture-route',model:'Route checkpoint',furthest_index:1,beat_brock:false,turns_used:700,provider:'custom-OLLAMA-route',family:'Fixture',cost_usd:99},
    {...sample[0],run_id:'fixture-start',model:'<img src=x onerror="window.injected=true">',furthest_index:-1,beat_brock:false,turns_used:300,cost_usd:null,tokens_in:null,tokens_out:null,wall_time_s:null,youtube_url:'javascript:alert(1)',milestones:[]},
    {...sample[0],run_id:'fixture-city',model:'Viridian stop',furthest_index:3,beat_brock:false,turns_used:50,run_date:'2026-09-08',timestamp:'20260908_120000'}
  ];
  await page.route('**/runs.json',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(fixture)}));
  await page.goto('http://127.0.0.1:8742/');
  await page.locator('#pewter .run-card').waitFor();
  check(await page.locator('#winners-wall .run-card').count()===0,'entered gym is not championship');
  check(await page.locator('#pewter .run-card[data-furthest="6"]').count()===1,'index six at Pewter');
  check(await page.locator('#route-one .run-card[data-furthest="1"]').count()===1,'index one at Route 1');
  check(await page.locator('#pallet .run-card[data-furthest="-1"]').count()===1,'no milestone at Red house');
  check(await page.locator('#viridian .run-card[data-furthest="3"]').count()===1,'Viridian station supported');
  check(!await page.locator('#sample-banner').isVisible() && await page.locator('.card-ribbon .sample-badge').count()===0,'real data has no illustrative badges');
  check(await page.evaluate(()=>!window.injected && document.querySelectorAll('.model-name img').length===0),'run content escaped');
  check((await page.locator('#pewter .stats').innerText()).includes('$0.00'),'zero-cost API is not FREE');
  check(await page.locator('#route-one .tag.local').count()===1,'provider containing Ollama classified local');
  check(await page.locator('#pewter a.inspect').getAttribute('href')==='https://www.youtube.com/watch?v=example','Inspect links to supplied VOD');
  check(await page.locator('#pallet .inspect:disabled').count()===1,'unsafe VOD URL disabled');
  await page.locator('#table-button').click();
  check(await page.locator('#table-cards .run-card[data-furthest="6"] .run-map circle[fill="#2dd4bf"]').count()===1,'only recorded milestones marked');
  check((await page.locator('#table-cards .run-card[data-furthest="-1"] .stats').innerText()).includes('—'),'unreported metrics preserved');
  await page.locator('#sort').selectOption('newest');
  check(await page.locator('#table-cards .model-name').first().innerText()==='Viridian stop','newest sort uses actual run date');
  await page.unroute('**/runs.json');
  await page.route('**/runs.json',route=>route.fulfill({status:404,body:'missing'}));
  await page.goto('http://127.0.0.1:8742/');
  await page.locator('#data-state h2').waitFor();
  check((await page.locator('#data-state').innerText()).includes('No runs yet — run the harness.'),'missing JSON friendly state');
  await page.unroute('**/runs.json');
  await page.route('**/runs.json',route=>route.fulfill({status:200,contentType:'application/json',body:'{broken'}));
  await page.reload();
  await page.locator('#data-state h2').waitFor();
  check((await page.locator('#data-state').innerText()).includes('unreadable'),'invalid JSON friendly state');
  await page.unroute('**/runs.json');
  await page.goto('http://127.0.0.1:8742/');
  await page.locator('#data-state h2').waitFor();
  check(errors.length===0,'no JavaScript errors: '+errors.join('; '));
  await page.screenshot({path:'.playwright-cli/verified-empty.png'});
  return {passed:results.length,checks:results,errors};
}